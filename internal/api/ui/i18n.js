function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* armazenamento indisponível */ }
  return (navigator.language || "").toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

let LANG = detectLang();

// Locale para números e datas (Intl).
function locale() { return LANG === "en" ? "en-US" : "pt-BR"; }

// t traduz key; vars preenche {parâmetros} ou é passado às funções.
function t(key, vars = {}) {
  const v = I18N[LANG][key] ?? I18N["pt-BR"][key];
  if (v === undefined) return key;
  if (typeof v === "function") return v(vars);
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// applyI18n traduz o HTML estático: data-i18n (texto), data-i18n-placeholder,
// data-i18n-aria (aria-label) e data-i18n-title.
function applyI18n(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}

function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  LANG = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* vale só nesta visita */ }
  document.documentElement.lang = lang;
  applyI18n();
}
